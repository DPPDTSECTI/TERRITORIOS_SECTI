-- Onda 1: estrutura institucional minima (estritamente aditiva)

DO $$
DECLARE
  v_ativos integer;
  v_35 integer;
  v_76 integer;
  v_ict integer;
BEGIN
  IF to_regclass('public.instituicoes') IS NOT NULL THEN
    RAISE EXCEPTION 'ABORTADO: public.instituicoes ja existe.';
  END IF;
  IF EXISTS (SELECT 1 FROM information_schema.columns WHERE table_schema='public' AND table_name='ativos_cti' AND column_name IN ('id_instituicao','parceiro_local')) THEN
    RAISE EXCEPTION 'ABORTADO: colunas id_instituicao/parceiro_local ja existem em ativos_cti.';
  END IF;
  SELECT COUNT(*) INTO v_ativos FROM public.ativos_cti;
  IF v_ativos <> 245 THEN
    RAISE EXCEPTION 'ABORTADO: esperado 245 ativos, encontrado %.', v_ativos;
  END IF;
  SELECT id_municipio INTO v_35 FROM public.ativos_cti WHERE id_ativo = 35;
  SELECT id_municipio INTO v_76 FROM public.ativos_cti WHERE id_ativo = 76;
  IF v_35 IS DISTINCT FROM 273 OR v_76 IS DISTINCT FROM 164 THEN
    RAISE EXCEPTION 'ABORTADO: saneamento 0.2.3 ausente (ID35=%, ID76=%).', v_35, v_76;
  END IF;
  SELECT COUNT(*) INTO v_ict FROM public.ativos_cti WHERE id_tipo_ativo = 3;
  IF v_ict <> 2 THEN
    RAISE EXCEPTION 'ABORTADO: esperado 2 ativos no tipo ICT, encontrado %.', v_ict;
  END IF;
END $$;

CREATE TABLE public.instituicoes (
  id_instituicao integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome_instituicao character varying(200) NOT NULL,
  sigla character varying(40),
  ict_status character varying(20) NOT NULL DEFAULT 'pendente',
  natureza_institucional character varying(80),
  site_oficial character varying(500),
  observacao_ict text,
  ativa boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT chk_instituicoes_nome_nao_vazio CHECK (length(btrim(nome_instituicao)) > 0),
  CONSTRAINT chk_instituicoes_sigla_nao_vazia CHECK (sigla IS NULL OR length(btrim(sigla)) > 0),
  CONSTRAINT chk_instituicoes_ict_status CHECK (ict_status IN ('sim', 'nao', 'pendente')),
  CONSTRAINT chk_instituicoes_site_url CHECK (site_oficial IS NULL OR site_oficial ~* '^https?://')
);

CREATE UNIQUE INDEX idx_unique_instituicao_nome_sigla
  ON public.instituicoes (
    lower(regexp_replace(btrim(nome_instituicao), '\s+', ' ', 'g')),
    COALESCE(lower(btrim(sigla)), '')
  );

CREATE INDEX idx_instituicoes_ict_status ON public.instituicoes (ict_status);

CREATE INDEX idx_instituicoes_sigla_norm
  ON public.instituicoes (lower(btrim(sigla)))
  WHERE sigla IS NOT NULL;

ALTER TABLE public.ativos_cti
  ADD COLUMN id_instituicao integer NULL,
  ADD COLUMN parceiro_local character varying(200) NULL;

ALTER TABLE public.ativos_cti
  ADD CONSTRAINT fk_ativos_instituicao
    FOREIGN KEY (id_instituicao)
    REFERENCES public.instituicoes (id_instituicao)
    ON DELETE RESTRICT
    ON UPDATE CASCADE,
  ADD CONSTRAINT chk_ativos_parceiro_local_valido
    CHECK (
      parceiro_local IS NULL
      OR (length(btrim(parceiro_local)) > 0 AND parceiro_local = btrim(parceiro_local))
    );

CREATE INDEX idx_ativos_cti_id_instituicao ON public.ativos_cti (id_instituicao);

ALTER TABLE public.instituicoes ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON TABLE public.instituicoes FROM PUBLIC, anon, authenticated;
REVOKE ALL ON SEQUENCE public.instituicoes_id_instituicao_seq FROM PUBLIC, anon, authenticated;
GRANT SELECT ON TABLE public.instituicoes TO anon, authenticated;

CREATE POLICY "Leitura Publica Instituicoes"
  ON public.instituicoes
  FOR SELECT
  TO anon, authenticated
  USING (true);

DO $$
DECLARE
  v_inst integer;
  v_vinc integer;
  v_total integer;
BEGIN
  SELECT COUNT(*) INTO v_inst FROM public.instituicoes;
  SELECT COUNT(*), COUNT(*) FILTER (WHERE id_instituicao IS NOT NULL OR parceiro_local IS NOT NULL)
    INTO v_total, v_vinc FROM public.ativos_cti;
  IF v_inst <> 0 OR v_vinc <> 0 OR v_total <> 245 THEN
    RAISE EXCEPTION 'POS-CONDICAO FALHOU: inst=%, vinculados=%, total=%.', v_inst, v_vinc, v_total;
  END IF;
  IF NOT (SELECT relrowsecurity FROM pg_class WHERE oid = 'public.instituicoes'::regclass) THEN
    RAISE EXCEPTION 'POS-CONDICAO FALHOU: RLS desabilitada.';
  END IF;
  IF EXISTS (
    SELECT 1 FROM information_schema.role_table_grants
    WHERE table_schema='public' AND table_name='instituicoes'
      AND grantee IN ('PUBLIC','anon','authenticated')
      AND privilege_type <> 'SELECT'
  ) THEN
    RAISE EXCEPTION 'POS-CONDICAO FALHOU: privilegio nao-SELECT para roles publicas.';
  END IF;
END $$;
